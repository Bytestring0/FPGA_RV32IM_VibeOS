#ifndef QW_TOOL_NORMALIZE_H
#define QW_TOOL_NORMALIZE_H

#include "ag_loop.h"

/* Bounds are UTF-8 bytes, not Unicode characters. All output capacities include NUL. */
#define QW_TOOL_TEXT_MAX 1024u
#define QW_NATIVE_ID_MAX 64u
#define QW_TOOL_MAP_MAX AG_LOOP_MAX_TURNS

typedef enum {
    QW_NORM_OK = 0, QW_NORM_INVALID, QW_NORM_LIMIT, QW_NORM_CONFLICT
} qw_norm_status;

typedef struct {
    char wire_id[AG_ID_MAX + 1];
    char native_id[QW_NATIVE_ID_MAX + 1]; /* empty if no native id supplied */
    char tool[32];
} qw_tool_identity;

typedef struct {
    uint32_t task_key; /* caller-provided unique key while any receipts may survive */
    uint32_t next_call;
    unsigned count;
    qw_tool_identity calls[QW_TOOL_MAP_MAX];
} qw_tool_normalizer;

/* task_key must be nonzero and unique across tasks sharing an ag_runtime. */
void qw_tool_normalizer_init(qw_tool_normalizer *state, uint32_t task_key);

/* Accept ONLY one complete <tool_call><function=...><parameter=...> call.
 * Pass the exact model-generated byte span (no chat framing or explanation).
 * native_id may be NULL when raw generated text has no native OpenAI call id.
 * runtime is reserved for callers; normalization does not inspect CPU state.
 * save_result.result_id is a UTF-8 string up to 192 bytes; ag_execute
 * decides whether it refers to a committed successful calculate (not_found).
 * No state/output is committed on failure; output[0] is cleared if possible.
 */
qw_norm_status qw_tool_normalize(qw_tool_normalizer *state,
    const ag_runtime *runtime, const char *generated, size_t generated_bytes,
    const char *native_id, char *output, size_t output_capacity);

/* Return NULL if the mapping does not exist (or the native id was unavailable). */
const char *qw_tool_native_id(const qw_tool_normalizer *state, const char *wire_id);
const char *qw_tool_wire_id(const qw_tool_normalizer *state, const char *native_id);

/* Format the real ag_execute receipt as the JSON content of a tool message.
 * Successful receipts must match a committed ag_runtime record verbatim.
 * Failed receipts have no committed record and must be supplied by ag_execute.
 * result_id exists ONLY for a committed successful calculate call.
 */
qw_norm_status qw_tool_format_receipt(const qw_tool_normalizer *state,
    const ag_runtime *runtime, const char *wire_id, const ag_receipt *receipt,
    char *output, size_t output_capacity);

#endif
