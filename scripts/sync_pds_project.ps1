param(
    [string]$Firmware = 'build\smoke.hex'
)
# Prepare the GUI project without running synthesis or changing source RTL.
$ErrorActionPreference = 'Stop'
$projectRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..')).Path
$projectPath = Join-Path $projectRoot 'RiscV.pds'
$generatedDirectory = Join-Path $projectRoot 'fpga\generated'
$backupDirectory = Join-Path $projectRoot 'fpga\backups'
$templatePath = Join-Path $projectRoot 'fpga\RiscV.template.pds'
$manifestPath = Join-Path $projectRoot 'rtl\files.f'
$firmwarePath = if ([IO.Path]::IsPathRooted($Firmware)) {
    $Firmware
} else {
    Join-Path $projectRoot $Firmware
}
if (!(Test-Path -LiteralPath $firmwarePath -PathType Leaf)) {
    throw "Firmware not found: $firmwarePath. Run make smoke or make coremark-build first."
}
if (!(Test-Path -LiteralPath $templatePath -PathType Leaf)) {
    throw "Project template not found: $templatePath"
}

$sourceNames = @(
    Get-Content -LiteralPath $manifestPath |
        ForEach-Object { $_.Trim() } |
        Where-Object { $_ -and !$_.StartsWith('#') -and !$_.StartsWith('//') }
)
if ($sourceNames -notcontains 'rtl/ag_fpga_top.sv') {
    $sourceNames += 'rtl/ag_fpga_top.sv'
}
$sourceNames = @($sourceNames | Select-Object -Unique)
$utf8 = [Text.UTF8Encoding]::new($false)
$combined = [Text.StringBuilder]::new()
[void]$combined.AppendLine('// Generated by scripts/sync_pds_project.ps1; edit rtl/*.sv, then regenerate.')
[void]$combined.AppendLine('// One compilation unit works around PDS 2022.2 package discovery limitations.')
foreach ($sourceName in $sourceNames) {
    $sourcePath = Join-Path $projectRoot $sourceName
    if (!(Test-Path -LiteralPath $sourcePath -PathType Leaf)) {
        throw "Manifest source not found: $sourcePath"
    }
    [void]$combined.AppendLine()
    [void]$combined.AppendLine("// Source: $sourceName")
    [void]$combined.AppendLine([IO.File]::ReadAllText($sourcePath))
}

New-Item -ItemType Directory -Force -Path $generatedDirectory, $backupDirectory | Out-Null
$backupPath = Join-Path $backupDirectory 'RiscV.before_gui_sync.pds'
if ((Test-Path -LiteralPath $projectPath) -and !(Test-Path -LiteralPath $backupPath)) {
    Copy-Item -LiteralPath $projectPath -Destination $backupPath
}
$combinedPath = Join-Path $generatedDirectory 'ag_all.sv'
[IO.File]::WriteAllText($combinedPath, $combined.ToString(), $utf8)
Copy-Item -LiteralPath $firmwarePath -Destination (Join-Path $projectRoot 'firmware.hex') -Force
$projectContents = [IO.File]::ReadAllText($templatePath)
$projectContents = $projectContents.Replace('__SOURCE_TIME__', (Get-Item -LiteralPath $combinedPath).LastWriteTime.ToString('yyyy-MM-ddTHH:mm:ss'))
$projectContents = $projectContents.Replace('__CONSTRAINT_TIME__', (Get-Item -LiteralPath (Join-Path $projectRoot 'fpga/timing.fdc')).LastWriteTime.ToString('yyyy-MM-ddTHH:mm:ss'))
[IO.File]::WriteAllText($projectPath, $projectContents, $utf8)

# Verify every external file referenced by the initial project is present.
$projectText = [IO.File]::ReadAllText($projectPath)
foreach ($fileMatch in [regex]::Matches($projectText, '\(_file "([^"]+)"')) {
    $referencePath = Join-Path $projectRoot $fileMatch.Groups[1].Value
    if (!(Test-Path -LiteralPath $referencePath -PathType Leaf)) {
        throw "Project references a missing file: $referencePath"
    }
}
Write-Output "GUI project prepared: $projectPath"
Write-Output "Top: ag_fpga_top; device: PG2L100H-6 FBG676; synthesis: ADS"
Write-Output "Combined $($sourceNames.Count) RTL sources into: $combinedPath"
Write-Output "Firmware copied from: $firmwarePath"
Write-Output 'Close the previously opened empty project without saving it, then reopen RiscV.pds.'
