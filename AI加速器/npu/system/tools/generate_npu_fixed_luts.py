#!/usr/bin/env python3
"""Offline-only LUT generation for NPU_FIXED_NUMERIC_VERSION 0x00010000.

Python real arithmetic is intentional here; the generated C data and consumer
contain only integers. Run explicitly after reviewing numeric-version changes:
    python system/tools/generate_npu_fixed_luts.py
No runtime/profile/model files are read or changed. No quality tests are run.
"""
from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path

VERSION = 0x00010000


def emit_array(name: str, c_type: str, values: list[int]) -> str:
    rows = [f"static const {c_type} {name}[{len(values)}] = {{"]
    for start in range(0, len(values), 12):
        rows.append("    " + ", ".join(str(v) for v in values[start:start + 12]) + ",")
    rows.append("};")
    return "\n".join(rows)


def generate_q16(output: Path) -> None:
    """Independent additive profile: never rewrites the original v1 tables."""
    version = 0x00010001
    xs = [i / 64.0 for i in range(1025)]
    tables = [
        ("npu_fixed_lut_sigmoid_q16", "uint32_t",
         [round(65536.0 / (1.0 + math.exp(-x))) for x in xs]),
        ("npu_fixed_lut_tanh_q16", "uint32_t",
         [round(65536.0 * math.tanh(x)) for x in xs]),
        ("npu_fixed_lut_silu_q16", "uint32_t",
         [round(65536.0 * x / (1.0 + math.exp(-x))) for x in xs]),
        ("npu_fixed_lut_softplus_q16", "uint32_t",
         [round(65536.0 * math.log1p(math.exp(x))) for x in xs]),
    ]
    payload = "\n\n".join(emit_array(*table) for table in tables)
    digest = hashlib.sha256(payload.encode("ascii")).hexdigest()
    storage_bytes = sum(len(values) * 4 for _, _, values in tables)
    text = f"""/* Generated by tools/generate_npu_fixed_luts.py --profile q16.
 * Independent additive Q16 activation LUT profile; original v1 is unchanged.
 * Offline binary64 math + round() (nearest, ties to even).
 * Numeric version: 0x{version:08x}; payload SHA256: {digest}
 * Read-only table storage: {storage_bytes} bytes before alignment.
 * Domain [0,16], knot spacing 1/64; signed arguments use exact symmetries.
 */
#ifndef NPU_FIXED_LUT_Q16_GENERATED_H
#define NPU_FIXED_LUT_Q16_GENERATED_H
#include <stdint.h>
#define NPU_FIXED_LUT_Q16_NUMERIC_VERSION UINT32_C(0x{version:08x})
#define NPU_FIXED_LUT_Q16_STORAGE_BYTES UINT32_C({storage_bytes})

{payload}

#endif
"""
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="ascii", newline="\n")
    print(f"Generated {output}")
    print(f"q16_numeric_version=0x{version:08x} storage_bytes={storage_bytes} sha256={digest}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", choices=("original", "q16"), default="original")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.profile == "q16":
        output = args.output or (Path(__file__).resolve().parents[1] / "sw" / "npu_fixed_lut_q16_generated.h")
        generate_q16(output)
        return
    if args.output is None:
        args.output = Path(__file__).resolve().parents[1] / "sw" / "npu_fixed_lut_generated.h"
    xs = [i / 64.0 for i in range(1025)]
    tables = [
        ("npu_fixed_lut_sigmoid_q12", "uint16_t",
         [round(4096.0 / (1.0 + math.exp(-x))) for x in xs]),
        ("npu_fixed_lut_tanh_q12", "uint16_t",
         [round(4096.0 * math.tanh(x)) for x in xs]),
        ("npu_fixed_lut_silu_q12", "uint32_t",
         [round(4096.0 * x / (1.0 + math.exp(-x))) for x in xs]),
        ("npu_fixed_lut_softplus_q12", "uint32_t",
         [round(4096.0 * math.log1p(math.exp(x))) for x in xs]),
        ("npu_fixed_lut_exp_negative_q30", "uint32_t",
         [round((1 << 30) * math.exp(-i / 256.0)) for i in range(4097)]),
        ("npu_fixed_lut_sine_quarter_q15", "uint16_t",
         [round(32768.0 * math.sin(math.pi * i / 2048.0)) for i in range(1025)]),
    ]
    payload = "\n\n".join(emit_array(*table) for table in tables)
    digest = hashlib.sha256(payload.encode("ascii")).hexdigest()
    storage_bytes = sum(len(v) * (2 if t == "uint16_t" else 4) for _, t, v in tables)
    text = f"""/* Generated by tools/generate_npu_fixed_luts.py; do not edit by hand.
 * Offline Python binary64 math + round() (nearest, ties to even).
 * Numeric version: 0x{VERSION:08x}; payload SHA256: {digest}
 * Read-only table storage: {storage_bytes} bytes (before alignment).
 * Activations: [0,16], step 1/64; exp: [-16,0], step 1/256;
 * sine quarter-wave: [0,1/4] turns, step 1/4096 turn.
 * These data are an opt-in numeric candidate, not model-quality validation.
 */
#ifndef NPU_FIXED_LUT_GENERATED_H
#define NPU_FIXED_LUT_GENERATED_H
#include <stdint.h>
#define NPU_FIXED_LUT_NUMERIC_VERSION UINT32_C(0x{VERSION:08x})
#define NPU_FIXED_LUT_STORAGE_BYTES UINT32_C({storage_bytes})

{payload}

#endif
"""
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(text, encoding="ascii", newline="\n")
    print(f"Generated {args.output}")
    print(f"numeric_version=0x{VERSION:08x} storage_bytes={storage_bytes} sha256={digest}")


if __name__ == "__main__":
    main()
