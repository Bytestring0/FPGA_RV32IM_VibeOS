def sha(path):
    digest = hashlib.sha256()
    with Path(path).open('rb') as source:
        for block in iter(lambda: source.read(1024 * 1024), b''):
            digest.update(block)
    return digest.hexdigest()


def save(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def command(argv, out, name):
    argv = list(map(str, argv))
    save(out / (name + '.command.json'), {'argv': argv, 'cwd': str(out)})
    with (out / (name + '.log')).open('wb') as log:
        result = subprocess.run(argv, cwd=out, stdout=log, stderr=subprocess.STDOUT, check=False)
    save(out / (name + '.result.json'), {'actual_exit': result.returncode, 'log_sha256': sha(out / (name + '.log'))})
    if result.returncode:
        raise RuntimeError(f'{name} failed with {result.returncode}; see {out / (name + ".log")}')


def deployment_header():
    lines = ['/* Exact immutable candidate pins. Generated by the dedicated builder. */']
    for key in ('weights', 'cpu', 'catalog'):
        symbol = {'weights': 'weight', 'cpu': 'cpu', 'catalog': 'catalog'}[key]
        values = ','.join('0x' + PINS[key]['sha256'][i:i + 2] for i in range(0, 64, 2))
        lines.append(f'static const uint8_t opt_{symbol}_sha[32] = {{{values}}};')
    names = [PINS[key]['short_name'] for key in ('weights', 'cpu', 'catalog')]
    # Exactly 11 DOS short-name bytes, without a trailing NUL.
    lines.append('static const char opt_sd_names[3][11] = {' + ','.join('{' + ','.join(str(ord(c)) for c in name) + '}' for name in names) + '};')
    lines.append('static const uint64_t opt_file_sizes[3] = {' + ','.join(str(PINS[key]['bytes']) + 'u' for key in ('weights', 'cpu', 'catalog')) + '};')
    return '\n'.join(lines) + '\n'


def verify_arch(out):
    attributes = (out / 'attributes.log').read_text(encoding='utf-8', errors='replace')
    match = re.search(r'Tag_RISCV_arch:\s*"([^"]+)"', attributes)
    if not match or not match[1].startswith('rv32i'):
        raise RuntimeError('Missing RV32 ISA attribute')
    extensions = {re.sub(r'[0-9].*$', '', x) for x in match[1][4:].split('_')}
    # GCC/libgcc can spell out zmmul, which is already a subset of M.
    if not {'i', 'm', 'zicsr', 'zifencei'} <= extensions or extensions - {'i', 'm', 'zicsr', 'zifencei', 'zmmul'}:
        raise RuntimeError(f'Unexpected ISA extensions: {match[1]}')
    header = (out / 'elf_header.log').read_text(encoding='utf-8', errors='replace')
    if not re.search(r'Class:\s+ELF32', header) or not re.search(r'Data:\s+.*little endian', header):
        raise RuntimeError('Firmware is not ELF32 little endian')
    if not re.search(r'Machine:\s+RISC-V', header) or not re.search(r'Flags:\s+0x0\b', header):
        raise RuntimeError('Firmware is not strict soft-float/RVC-free RISC-V ILP32')
    return match[1]
